"""Writes crates/cua-eval/src/font_data.rs: the 95 printable ASCII glyphs as 8x16 bitmaps, cut
from Hack Regular (MIT) at 13 px with no anti-aliasing. Run: uv run --with pillow
scripts/dev/gen-eval-font.py <Hack-Regular.ttf> > crates/cua-eval/src/font_data.rs"""
import sys
from PIL import Image, ImageDraw, ImageFont

font = ImageFont.truetype(sys.argv[1], 13)
print("//! The glyphs of the fake surfaces' screens: 95 printable ASCII characters, 8x16, one byte a")
print("//! row, most significant bit leftmost. Generated by scripts/dev/gen-eval-font.py from Hack")
print("//! Regular (MIT licence, Bitstream Vera and DejaVu terms for the outlines).")
print()
print("/// Glyph rows for the characters from space to tilde.")
print("pub(crate) const GLYPHS: [[u8; 16]; 95] = [")
for code in range(32, 127):
    img = Image.new("L", (8, 16), 0)
    ImageDraw.Draw(img).text((0, -1), chr(code), font=font, fill=255)
    rows = []
    for y in range(16):
        bits = 0
        for x in range(8):
            bits = (bits << 1) | (1 if img.getpixel((x, y)) >= 110 else 0)
        rows.append(bits)
    print("    [" + ", ".join(f"0x{b:02x}" for b in rows) + f"], // {chr(code)!r}")
print("];")
